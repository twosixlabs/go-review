func assessmentReport(t *testing.T, src string) *Report {
	t.Helper()
	formatted, err := format.Source([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	return &Report{
		SourceSHA256: "source-revision",
		Packages:     []Package{{Path: "example/app", FileIDs: []string{"file"}}},
		Files:        []File{{ID: "file", Package: "example/app", Path: "app.go", Source: string(formatted)}},
	}
}

func TestAssessmentSourceFindingsAndProvenance(t *testing.T) {
	r := assessmentReport(t, `package app
func cloneState() {}
func Check(x bool) {
 cloneState()
 `+strings.Repeat("if x { println(x) }\n", 14)+`
}`)
	r.Symbols = []Symbol{{ID: "check", Package: "example/app", Name: "Check", Kind: "function",
		Cyclomatic: 15, Location: Location{FileID: "file", Line: 5, EndLine: 50}}}
	result := Assess(r)
	if result.SourceSHA256 != "source-revision" || result.Version == "" {
		t.Fatalf("missing provenance: %+v", result)
	}
	found := map[string]bool{}
	for _, finding := range result.Findings {
		found[finding.RuleID] = true
		if finding.Location.FileID != "file" || finding.Location.Line < 1 || finding.ID == "" {
			t.Fatalf("finding lost source evidence: %+v", finding)
		}
	}
	if !found["ownership-plumbing"] || found["complexity"] {
		t.Fatalf("missing rules: %+v", result.Findings)
	}
	if result.Packages[0].Level != "watch" {
		t.Fatalf("rating=%s", result.Packages[0].Level)
	}
	for _, check := range result.Checks {
		if check.ID == "repository-hygiene" || check.ID == "vet" || check.ID == "tests" || check.ID == "deadcode" {
			if check.Status != "not-run" {
				t.Fatalf("invented execution: %+v", check)
			}
		}
	}
}

func TestConcernLevelUsesSeverityAndDistinctAffectedFunctions(t *testing.T) {
	for _, tc := range []struct {
		name     string
		count    int
		findings []SignalFinding
		want     string
	}{
		{"clear", 10, nil, "clear"},
		{"watch", 10, []SignalFinding{{Severity: "low", SymbolID: "a"}}, "watch"},
		{"significant", 10, []SignalFinding{{Severity: "medium", SymbolID: "a"}}, "concern"},
		{"severe", 10, []SignalFinding{{Severity: "high", SymbolID: "a"}}, "high-concern"},
		{"same function not widespread", 10, []SignalFinding{{Severity: "medium", SymbolID: "a"}, {Severity: "medium", SymbolID: "a"}, {Severity: "medium", SymbolID: "a"}}, "concern"},
		{"recurring significant", 10, []SignalFinding{{Severity: "medium", SymbolID: "a"}, {Severity: "medium", SymbolID: "b"}, {Severity: "medium", SymbolID: "c"}}, "high-concern"},
		{"sparse significant", 100, []SignalFinding{{Severity: "medium", SymbolID: "a"}, {Severity: "medium", SymbolID: "b"}, {Severity: "medium", SymbolID: "c"}}, "concern"},
		{"at twenty percent", 15, []SignalFinding{{Severity: "medium", SymbolID: "a"}, {Severity: "medium", SymbolID: "b"}, {Severity: "medium", SymbolID: "c"}}, "high-concern"},
		{"below twenty percent", 16, []SignalFinding{{Severity: "medium", SymbolID: "a"}, {Severity: "medium", SymbolID: "b"}, {Severity: "medium", SymbolID: "c"}}, "concern"},
		{"recurring low", 10, []SignalFinding{{Severity: "low", SymbolID: "a"}, {Severity: "low", SymbolID: "b"}, {Severity: "low", SymbolID: "c"}}, "concern"},
		{"empty scope", 0, nil, "not-assessed"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := concernLevel(tc.count, tc.findings); got != tc.want {
				t.Fatalf("got %s want %s", got, tc.want)
			}
		})
	}
}

func TestAssessmentExcludesGeneratedAndTestFilesAndDoesNotCertifyBrokenSource(t *testing.T) {
	r := assessmentReport(t, "package app\nfunc F() {}")
	r.Files = append(r.Files,
		File{ID: "generated", Package: "example/app", Path: "generated.go", Source: "// Code generated by tool. DO NOT EDIT.\npackage app\nfunc copyThing(){}"},
		File{ID: "test", Package: "example/app", Path: "app_test.go", Source: "package app\nfunc copyThing(){}"},
	)
	r.Symbols = []Symbol{
		{ID: "f", Package: "example/app", Kind: "function", Cyclomatic: 1, Location: Location{FileID: "file", Line: 3, EndLine: 3}},
		{ID: "generated-f", Package: "example/app", Kind: "function", Cyclomatic: 90, Location: Location{FileID: "generated", Line: 3, EndLine: 3}},
	}
	result := Assess(r)
	if len(result.Findings) != 0 || result.Packages[0].Functions != 1 || result.Packages[0].Level != "clear" {
		t.Fatalf("excluded source affected rating: %+v", result)
	}
	r.Files[0].Source = "package app\nfunc Broken("
	result = Assess(r)
	if result.Packages[0].Level != "not-assessed" {
		t.Fatalf("broken source marked %s", result.Packages[0].Level)
	}
}

