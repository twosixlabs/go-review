func TestAgentSourcesDecodeReportsWithoutTestSources(t *testing.T) {
	var report Report
	if err := json.Unmarshal([]byte(`{"schemaVersion":"1","files":[]}`), &report); err != nil {
		t.Fatal(err)
	}
	if reportTestSourcesJSON(t, &report)["testSources"] != nil {
		t.Fatal("legacy report without test-source data must not fabricate a test inventory")
	}
}

func agentTestSourceRecords(t *testing.T, report *Report) []map[string]any {
	t.Helper()
	wire := reportTestSourcesJSON(t, report)
	value, ok := wire["testSources"].([]any)
	if !ok {
		t.Fatalf("report has no serialized test sources: %s", mustJSON(t, wire))
	}
	sources := make([]map[string]any, 0, len(value))
	for _, item := range value {
		source, ok := item.(map[string]any)
		if !ok {
			t.Fatalf("invalid test source record: %#v", item)
		}
		sources = append(sources, source)
	}
	return sources
}

func reportTestSourcesJSON(t *testing.T, report *Report) map[string]any {
	t.Helper()
	data, err := json.Marshal(report)
	if err != nil {
		t.Fatal(err)
	}
	var wire map[string]any
	if err := json.Unmarshal(data, &wire); err != nil {
		t.Fatal(err)
	}
	return wire
}

func declarationRecords(t *testing.T, source map[string]any) []map[string]any {
	t.Helper()
	value, ok := source["declarations"].([]any)
	if !ok {
		t.Fatalf("test source has no declarations: %#v", source)
	}
	declarations := make([]map[string]any, 0, len(value))
	for _, item := range value {
		declaration, ok := item.(map[string]any)
		if !ok {
			t.Fatalf("invalid declaration record: %#v", item)
		}
		declarations = append(declarations, declaration)
	}
	return declarations
}

func mapKeys[K comparable, V any](m map[K]V) []K {
	keys := make([]K, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	return keys
}

func mustJSON(t *testing.T, value any) string {
	t.Helper()
	data, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func agentSourcesFixtureRoot(t *testing.T) string {
	t.Helper()
	if err := os.MkdirAll(".work", 0700); err != nil {
		t.Fatal(err)
	}
	name := filepath.Join(".work", "agent-source-tests-"+strconv.Itoa(os.Getpid())+"-"+strings.ReplaceAll(t.Name(), "/", "-"))
	root, err := filepath.Abs(name)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(root, 0700); err != nil {
		t.Fatalf("create fixture directory %s: %v", root, err)
	}
	t.Cleanup(func() {
		if err := os.RemoveAll(root); err != nil {
			t.Errorf("remove fixture directory %s: %v", root, err)
		}
	})
	return root
}

func snapshotAgentFixtureFiles(t *testing.T, root string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.WalkDir(root, func(name string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, name)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		files[filepath.ToSlash(rel)] = data
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func assertAgentFixtureUnchanged(t *testing.T, root string, before map[string][]byte) {
	t.Helper()
	after := snapshotAgentFixtureFiles(t, root)
	if len(after) != len(before) {
		t.Fatalf("analysis changed fixture file inventory: before=%v after=%v", mapKeys(before), mapKeys(after))
	}
	for path, content := range before {
		if !bytes.Equal(content, after[path]) {
			t.Errorf("analysis changed fixture source %s", path)
		}
	}
}
