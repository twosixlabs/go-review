func TestAgentSourcesIncludeDeclarationsAndWithholdExcludedBodies(t *testing.T) {
	root := agentSourcesFixtureRoot(t)
	writeReviewFixture(t, root, "go.mod", "module example.com/agentsources\n\ngo 1.24\n")
	writeReviewFixture(t, root, "app.go", "package agentsources\nfunc Production() {}\n")
	writeReviewFixture(t, root, "app_test.go", `package agentsources
import ("os"; "testing")
func TestIncluded(t *testing.T) { func() { t.Log("included closure") }() }
func TestExcluded(t *testing.T) { func() { os.WriteFile("executed", nil, 0600) }() }
func Testhelper(t *testing.T) {}
func helper() {}
type testReceiver struct{}
func (testReceiver) TestMethod(t *testing.T) {}
func init() { os.WriteFile("init-executed", nil, 0600) }
`)
	writeReviewFixture(t, root, "external_test.go", `package agentsources_test
import "testing"
func TestExternal(t *testing.T) {}
`)
	writeReviewFixture(t, root, "generated_test.go", "// Code generated by fixture. DO NOT EDIT.\npackage agentsources\nimport \"testing\"\nfunc TestGenerated(t *testing.T) {}\n")
	writeReviewFixture(t, root, "header_generated_test.go", "// Generated by `wit-bindgen` 0.61.1. DO NOT EDIT!\npackage agentsources\nimport \"testing\"\nfunc TestHeaderGenerated(t *testing.T) {}\n")
	writeReviewFixture(t, root, "tools/tools.go", "package tools\nfunc Tool() {}\n")
	writeReviewFixture(t, root, "tools/tools_test.go", "package tools\nimport \"testing\"\nfunc TestPathExcluded(t *testing.T) {}\n")
	writeReviewFixture(t, root, "inactive_test.go", "//go:build never\n\npackage agentsources\nimport \"testing\"\nfunc TestInactive(t *testing.T) {}\n")

	scope := ReviewScope{Root: root, ExcludePaths: []string{"generated_test.go", "tools"}, ExcludeTests: []string{"^Test(Excluded|Method)$"}}
	before := snapshotAgentFixtureFiles(t, root)
	report, err := Analyze(context.Background(), Options{Dir: root, DocumentationDir: root, Scope: &scope})
	if err != nil {
		t.Fatal(err)
	}
	assertAgentFixtureUnchanged(t, root, before)
	sources := agentTestSourceRecords(t, report)
	found := map[string]map[string]any{}
	for _, source := range sources {
		file := source["file"].(map[string]any)
		found[file["path"].(string)] = source
	}
	if len(found) != 2 {
		t.Fatalf("want only active, included test files; got %v", mapKeys(found))
	}
	for _, excluded := range []string{"generated_test.go", "header_generated_test.go", "tools/tools_test.go", "inactive_test.go"} {
		if _, ok := found[excluded]; ok {
			t.Errorf("excluded test source %q was captured", excluded)
		}
	}

	inPackage, ok := found["app_test.go"]
	if !ok {
		t.Fatalf("missing in-package test source: %v", mapKeys(found))
	}
	file := inPackage["file"].(map[string]any)
	if got := file["id"]; got != stableID("file", "example.com/agentsources/app_test.go") {
		t.Errorf("unstable in-package file ID: %v", got)
	}
	declarations := declarationRecords(t, inPackage)
	kinds := map[string]string{}
	for _, declaration := range declarations {
		kinds[declaration["name"].(string)] = declaration["kind"].(string)
	}
	for name, want := range map[string]string{
		"TestIncluded": "test", "TestExcluded": "test", "Testhelper": "helper",
		"helper": "helper", "TestMethod": "helper",
	} {
		if kinds[name] != want {
			t.Errorf("%s kind = %q, want %q", name, kinds[name], want)
		}
	}
	if _, ok := kinds["TestInactive"]; ok {
		t.Error("inactive build-tag source was included")
	}
	excluded := inPackage["excludedRanges"].([]any)
	if len(excluded) != 1 {
		t.Fatalf("only the excluded entry point body and its nested closure need protection, got %v", excluded)
	}
	rng := excluded[0].(map[string]any)
	sourceText := file["source"].(string)
	start, end := int(rng["offset"].(float64)), int(rng["endOffset"].(float64))
	if start < 0 || end <= start || !strings.Contains(sourceText[start:end], "executed") || strings.Contains(sourceText[:start], "TestExcluded(t") || !strings.Contains(sourceText[start:end], "os.WriteFile") {
		t.Fatalf("excluded byte range does not cover the declaration and closure: %v", rng)
	}

	externalSource, ok := found["external_test.go"]
	if !ok {
		t.Fatalf("missing external test package source: %v", mapKeys(found))
	}
	external := externalSource["file"].(map[string]any)
	if external["package"] != "example.com/agentsources_test" || external["id"] != stableID("file", "example.com/agentsources_test/external_test.go") {
		t.Errorf("external test package identity is incorrect: %+v", external)
	}
	if len(report.Files) != 1 || report.Files[0].Path != "app.go" {
		t.Errorf("test sources leaked into production files: %+v", report.Files)
	}
	if len(report.Packages) != 1 || len(report.Packages[0].FileIDs) != 1 || report.Packages[0].FileIDs[0] != report.Files[0].ID {
		t.Errorf("test files changed production package membership: %+v", report.Packages)
	}
	for _, symbol := range report.Symbols {
		if strings.HasPrefix(symbol.Name, "Test") || symbol.Name == "helper" {
			t.Errorf("test declaration leaked into production symbols: %+v", symbol)
		}
	}
	if report.Coverage != nil || report.Trace != nil {
		t.Errorf("static test snapshots must not imply execution evidence: coverage=%v trace=%v", report.Coverage, report.Trace)
	}
	for _, marker := range []string{"executed", "init-executed"} {
		if _, err := os.Stat(filepath.Join(root, marker)); !os.IsNotExist(err) {
			t.Errorf("Analyze executed target test code (%s: %v)", marker, err)
		}
	}
}

