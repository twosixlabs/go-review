func TestAgentSourcesReportMalformedTestSource(t *testing.T) {
	root := agentSourcesFixtureRoot(t)
	writeReviewFixture(t, root, "go.mod", "module example.com/agentmalformed\n\ngo 1.24\n")
	writeReviewFixture(t, root, "app.go", "package agentmalformed\nfunc Production() {}\n")
	writeReviewFixture(t, root, "broken_test.go", "package agentmalformed\nfunc TestBroken( {\n")
	report, err := Analyze(context.Background(), Options{Dir: root, DocumentationDir: root})
	if err != nil {
		t.Fatal(err)
	}
	sources := agentTestSourceRecords(t, report)
	if len(sources) != 1 || sources[0]["file"].(map[string]any)["path"] != "broken_test.go" {
		t.Fatalf("malformed source was mistaken for a repository with no tests: %v", sources)
	}
	foundDiagnostic := false
	for _, warning := range report.Warnings {
		if strings.Contains(warning, "broken_test.go") {
			foundDiagnostic = true
		}
	}
	if !foundDiagnostic {
		t.Fatalf("malformed test source has no visible diagnostic: %v", report.Warnings)
	}
}

func TestAgentSourcesAreFreshnessCheckedAndHashedOnceAcrossUnitCollection(t *testing.T) {
	root := agentSourcesFixtureRoot(t)
	writeReviewFixture(t, root, "go.mod", "module example.com/agenttrace\n\ngo 1.24\n")
	writeReviewFixture(t, root, "app.go", "package agenttrace\nfunc Value() int { return 7 }\n")
	writeReviewFixture(t, root, "app_test.go", "package agenttrace\nimport \"testing\"\nfunc TestValue(t *testing.T) { if Value()!=7 { t.Fatal(\"bad\") } }\n")
	first, err := Analyze(context.Background(), Options{Dir: root, DocumentationDir: root})
	if err != nil {
		t.Fatal(err)
	}
	if err := verifyDataSources(context.Background(), first); err != nil {
		t.Fatalf("fresh test source rejected: %v", err)
	}
	writeReviewFixture(t, root, "app_test.go", "package agenttrace\nimport \"testing\"\nfunc TestValue(t *testing.T) { if Value()!=8 { t.Fatal(\"bad\") } }\n")
	if err := verifyDataSources(context.Background(), first); err == nil {
		t.Fatal("modified test source was accepted as the original snapshot")
	}
	second, err := Analyze(context.Background(), Options{Dir: root, DocumentationDir: root})
	if err != nil {
		t.Fatal(err)
	}
	if first.SourceSHA256 == second.SourceSHA256 {
		t.Fatal("test source changes did not change the report snapshot hash")
	}
	artifactDir := t.TempDir()
	beforeTrace := snapshotAgentFixtureFiles(t, root)
	snapshotHash := second.SourceSHA256
	staticSource := second.TestSources[0].File
	err = CollectUnitEvidence(context.Background(), second, UnitEvidenceOptions{ArtifactDir: artifactDir, Selections: []UnitTestSelection{{Package: second.Module, Tests: []string{"TestValue"}}}})
	if err == nil {
		t.Fatal("the deliberately changed test should fail and retain partial evidence")
	}
	assertAgentFixtureUnchanged(t, root, beforeTrace)
	if second.SourceSHA256 != snapshotHash {
		t.Fatalf("unit collection changed source identity: before=%s after=%s", snapshotHash, second.SourceSHA256)
	}
	if second.TestSources[0].File.SHA256 != staticSource.SHA256 || !strings.Contains(second.TestSources[0].File.Source, "func TestValue") {
		t.Fatal("selected test source provenance lost")
	}
	for _, s := range second.Symbols {
		if s.Name == "TestValue" {
			t.Fatal("test provenance became a production graph symbol")
		}
	}
}

func TestAgentSourcesNameExclusionDoesNotHideTestNamedHelperMethod(t *testing.T) {
	root := agentSourcesFixtureRoot(t)
	writeReviewFixture(t, root, "go.mod", "module example.com/agentmethod\n\ngo 1.24\n")
	writeReviewFixture(t, root, "app.go", "package agentmethod\nfunc Production() {}\n")
	writeReviewFixture(t, root, "app_test.go", `package agentmethod
import "testing"
type fixture struct{}
func (fixture) TestMethod(t *testing.T) {}
func TestUse(t *testing.T) { fixture{}.TestMethod(t) }
`)
	scope := ReviewScope{Root: root, ExcludeTests: []string{"^TestMethod$"}}
	artifactDir := t.TempDir()
	report, err := Analyze(context.Background(), Options{Dir: root, DocumentationDir: root, Scope: &scope})
	if err != nil {
		t.Fatal(err)
	}
	if err = CollectUnitEvidence(context.Background(), report, UnitEvidenceOptions{ArtifactDir: artifactDir, Selections: []UnitTestSelection{{Package: report.Module, Tests: []string{"TestUse"}}}}); err != nil {
		t.Fatal(err)
	}
	if len(report.TestSources) != 1 {
		t.Fatalf("missing source snapshot: %+v", report.TestSources)
	}
	foundMethod := false
	for _, symbol := range report.TestSources[0].Declarations {
		if symbol.Name == "TestMethod" && symbol.Kind == "helper" {
			foundMethod = true
		}
	}
	if !foundMethod {
		t.Fatalf("test-named helper method was incorrectly removed by name-based test exclusion: symbols=%+v sources=%+v", report.Symbols, report.TestSources)
	}
}

