func TestScopePatternsAndPersistence(t *testing.T) {
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	scope := ReviewScope{ExcludePaths: []string{"server/cmd/bench-*", "**/smoke_test.go", "scripts/verify-repository.sh"}, ExcludeTests: []string{"^TestPerformance"}}
	if err := SaveReviewScope(root, scope); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		name, e := scopeConfigPath(root)
		if e == nil {
			if e = os.Remove(name); e != nil {
				t.Error(e)
			}
		}
	})
	saved, err := LoadReviewScope(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{"server/cmd/bench-one/main.go", "server/internal/app/smoke_test.go", "smoke_test.go", "scripts/verify-repository.sh"} {
		if saved.pathReason(path) == "" {
			t.Errorf("did not exclude %s", path)
		}
	}
	if saved.pathReason("server/cmd/builder/main.go") != "" {
		t.Fatal("scope excluded unrelated application code")
	}
	for _, invalid := range []string{"../outside", "/absolute", "bad[pattern", "."} {
		if err := SaveReviewScope(root, ReviewScope{ExcludePaths: []string{invalid}}); err == nil {
			t.Errorf("accepted invalid exclusion %q", invalid)
		}
	}
	if err := SaveReviewScope(root, ReviewScope{ExcludeTests: []string{"["}}); err == nil {
		t.Fatal("invalid regex accepted")
	}
}

func TestScopeGeneratedAndExplicitEvidence(t *testing.T) {
	root := t.TempDir()
	writeReviewFixture(t, root, "go.mod", "module example.com/scoped\n\ngo 1.24\n")
	writeReviewFixture(t, root, "app.go", "package scoped\nfunc App() int { return Generated() }\n")
	writeReviewFixture(t, root, "generated.go", "// Generated by `wit-bindgen` 0.61.1. DO NOT EDIT!\npackage scoped\nfunc Generated() int {return 1}\n")
	writeReviewFixture(t, root, "tools/smoke.go", "package tools\nfunc Smoke() {}\n")
	writeReviewFixture(t, root, "tools/README.md", "# Excluded smoke tooling\n")
	scope := ReviewScope{Root: root, ExcludePaths: []string{"tools"}}
	r, err := Analyze(context.Background(), Options{Dir: root, Scope: &scope})
	if err != nil {
		t.Fatal(err)
	}

	if len(r.Files) != 1 || len(r.Packages) != 1 {
		t.Fatalf("out-of-scope evidence leaked: %d files, %d packages", len(r.Files), len(r.Packages))
	}
	for _, s := range r.Symbols {
		if s.Name == "Generated" || s.Name == "Smoke" {
			t.Fatalf("excluded symbol leaked: %s", s.Name)
		}
	}
	if len(r.Exclusions) < 2 {
		t.Fatalf("missing exclusion inventory: %+v", r.Exclusions)
	}
	boundary := false
	for _, c := range r.Calls {
		if strings.Contains(c.Target, "Generated") {
			boundary = c.To == "" && strings.Contains(c.Reason, "scope")
		}
	}
	if !boundary {
		t.Fatal("excluded callee must remain an explicit boundary call")
	}
	profile := "mode: set\nexample.com/scoped/app.go:2.16,2.38 1 1\nexample.com/scoped/generated.go:3.22,3.32 99 0\n"
	if err = ImportCoverage(r, strings.NewReader(profile), "fixture"); err != nil {
		t.Fatal(err)
	}
	if r.Coverage.Statements != 1 || r.Coverage.CoveredStatements != 1 {
		t.Fatalf("excluded source diluted coverage: %+v", r.Coverage)
	}
	if err = verifyDataSources(context.Background(), r); err != nil {
		t.Fatal(err)
	}
	if len(r.Documents) != 0 {
		t.Fatal("excluded tooling documentation leaked into review")
	}
	if _, err = AnalyzeDataFlow(context.Background(), r, symbol(t, r, "App").ID); err != nil {
		t.Fatalf("generated support source must remain usable for handwritten SSA: %v", err)
	}
	for i := range r.SupportingFiles {
		if r.SupportingFiles[i].Path == "generated.go" {
			r.SupportingFiles[i].Source += "\n// tampered embedded source\n"
		}
	}
	if err = verifyDataSources(context.Background(), r); err == nil {
		t.Fatal("tampered embedded support source accepted")
	}
}

func TestScopeDirectExecutionAndAuthoritativeHook(t *testing.T) {
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}

	writeReviewFixture(t, root, "go.mod", "module example.com/execute\n\ngo 1.24\n")
	writeReviewFixture(t, root, "app.go", "package execute\nfunc Value() int {return 1}\nfunc PerformanceOnly() {}\n")
	writeReviewFixture(t, root, "generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage execute\nimport \"fmt\"\nfunc GeneratedNoise() {fmt.Printf(\"%d\", \"not an int\")}\n")
	writeReviewFixture(t, root, "app_test.go", `package execute
	import ("os";"testing";"fmt")
	func TestIncluded(t *testing.T) {Testhelper(t);if Value()!=1 {t.Fatal("bad")}}
	func Testhelper(t *testing.T) {if Value()!=1 {t.Fatal("helper failed")}}
	func TestPerformance(t *testing.T) {func(){PerformanceOnly()}();fmt.Printf("%d", "excluded vet noise");os.WriteFile("forbidden-name",nil,0600);t.Fatal("excluded")}
	`)
	writeReviewFixture(t, root, "smoke_test.go", `package execute
	import ("os";"testing")
	func TestSmoke(t *testing.T) {os.WriteFile("forbidden-file",nil,0600);t.Fatal("excluded")}
	`)
	writeReviewFixture(t, root, "generated_test.go", "// Generated by `wit-bindgen` 0.61.1. DO NOT EDIT!\npackage execute\nimport \"testing\"\nfunc TestGenerated(t *testing.T) {t.Fatal(\"excluded generated test\")}\n")
	writeReviewFixture(t, root, "cmd/bench/main.go", "package main\nfunc main() {}\n")
	writeReviewFixture(t, root, "cmd/bench/main_test.go", "package main\nimport \"testing\"\nfunc TestBench(t *testing.T) {t.Fatal(\"excluded package\")}\n")
	writeReviewFixture(t, root, "scripts/verify-repository.sh", "#!/bin/sh\nprintf 'authoritative script ran\\n'\n")
	scope := ReviewScope{ExcludePaths: []string{"smoke_test.go", "cmd/bench"}, ExcludeTests: []string{"^TestPerformance$", "^Testhelper$"},
		UnitSelections: []UnitTestSelection{{Package: "example.com/execute", Tests: []string{"TestIncluded"}}}, VerifyRepository: true}
	if err = SaveReviewScope(root, scope); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		name, e := scopeConfigPath(root)
		if e == nil {
			os.Remove(name)
		}
	})
	run, err := ReviewRepository(context.Background(), root, t.TempDir(), nil)
	if err != nil {
		t.Fatal(err)
	}
	r := run.Modules[0].Report
	if r == nil || r.UnitEvidence == nil || r.UnitEvidence.Runs[0].Status != "pass" || r.Trace != nil {
		t.Fatalf("scoped review failed: %+v", run.Steps)
	}
	for _, name := range []string{"forbidden-name", "forbidden-file"} {
		if _, err = os.Stat(filepath.Join(root, name)); !os.IsNotExist(err) {
			t.Fatalf("excluded test ran: %s (%v)", name, err)
		}
	}
	for _, s := range r.Symbols {
		if s.Name == "TestPerformance" || s.Name == "TestSmoke" || s.Name == "TestGenerated" {
			t.Fatalf("excluded recorded function leaked: %s", s.Name)
		}
	}
	for _, c := range r.Calls {
		if strings.Contains(c.Target, "PerformanceOnly") {
			t.Fatalf("excluded test body leaked into normal call graph: %+v", c)
		}
	}
	for _, step := range run.Steps {
		if step.ID == "vet" && step.Status != "pass" {
			t.Fatalf("generated vet findings leaked into scope: %s %s", step.Status, step.Detail)
		}
		if step.ID == "deadcode" && !strings.Contains(step.Detail, "PerformanceOnly") {
			t.Fatalf("excluded test still used as a reachability root: %s", step.Detail)
		}
		if step.ID == "repository-hygiene" && len(step.Commands) != 1 {
			t.Fatal("test exclusions suppressed the authoritative hook")
		}
	}
	scope.ExcludePaths = append(scope.ExcludePaths, "scripts/verify-repository.sh")
	if err = SaveReviewScope(root, scope); err != nil {
		t.Fatal(err)
	}
	run, err = ReviewRepository(context.Background(), root, t.TempDir(), nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, step := range run.Steps {
		if step.ID == "repository-hygiene" && (step.Status != "not-run" || len(step.Commands) != 0) {
			t.Fatal("explicit script exclusion ignored")
		}
	}
}
