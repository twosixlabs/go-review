const test=require('node:test');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const fs=require('node:fs');
const path=require('node:path');
const tools=require('./assessment-tools.js');

function report() {
  return {sourceSHA256:'current',assessment:{version:'architecture-signals/1',sourceSHA256:'current',
    packages:[{package:'app/a',level:'watch',files:1,functions:2},{package:'app/b',level:'high-concern',files:2,functions:5},
      {package:'app/c',level:'not-assessed',files:0,functions:0}],
    findings:[{id:'one',package:'app/a',symbolID:'f',severity:'low',ruleID:'forwarding',summary:'<script>not trusted</script>',evidence:'one boundary',location:{fileID:'file',line:4}},
      {id:'two',package:'app/b',symbolID:'g',severity:'high',ruleID:'wide-interface',summary:'Wide contract',evidence:'20 methods',location:{fileID:'other',line:8}}],
    checks:[{id:'format',title:'Formatting',status:'pass',detail:'source inspected',locations:[]},
      {id:'syntax',title:'Syntax',status:'error',detail:'invalid source',locations:[]},
      {id:'vet',title:'Vet',status:'not-run',detail:'not executed',locations:[]},
      {id:'policy',title:'Policy',status:'fail',detail:'policy violation',locations:[]}]
  }};
}

test('architecture summary uses worst package without hiding unassessed scope',()=>{
  const model=tools.model(report());
  assert.equal(model.level,'high-concern');
  assert.equal(model.assessed,2);
  assert.equal(model.total,3);
  assert.deepEqual(model.hygiene,{passed:1,completed:2,errors:1,notRun:1});
  const filtered=tools.model(report(),'app/a');
  assert.equal(filtered.level,'watch');
  assert.deepEqual(filtered.findings.map(f=>f.id),['one']);
});

test('absent or stale architecture evidence never appears clear',()=>{
  assert.equal(tools.model({}).level,'not-assessed');
  const r=report();r.sourceSHA256='changed';
  assert.equal(tools.model(r).level,'not-assessed');
  assert.equal(tools.model(r).findings.length,0);
  assert.equal(tools.model(report(),'missing').level,'not-assessed');
  const missingHash=report();
  delete missingHash.sourceSHA256;delete missingHash.assessment.sourceSHA256;
  assert.equal(tools.model(missingHash).level,'not-assessed');
});

test('architecture evidence table shows check errors and source drill-down without executing source HTML',()=>{
  const dom=new JSDOM('<main></main>');
  const container=dom.window.document.querySelector('main');
  let selected,scope;
  tools.render(container,report(),{onFinding:f=>{selected=f.id;},onPackage:path=>{scope=path;}});
  assert.match(container.textContent,/High concern/);
  assert.match(container.textContent,/1\/2 completed checks passed/);
  assert.match(container.textContent,/1 error/);
  assert.match(container.textContent,/Not run/);
  assert.equal(container.querySelectorAll('script').length,0);
  container.querySelector('[data-finding="one"]').click();
  assert.equal(selected,'one');
  container.querySelector('[data-package="app/a"]').click();
  assert.equal(scope,'app/a');
  dom.window.close();
});

test('contextual findings follow symbol or source range instead of leaking sibling findings',()=>{
  const r=report();
  assert.deepEqual(tools.contextFindings(r,{symbolID:'f'}).map(f=>f.id),['one']);
  assert.deepEqual(tools.contextFindings(r,{location:{fileID:'other',line:8,endLine:8}}).map(f=>f.id),['two']);
  assert.deepEqual(tools.contextFindings(r,{symbolID:'unmatched'}),[]);
});

test('node architecture is scoped to its owner, not the worst sibling or whole package',()=>{
  const r=report();
  r.symbols=[{id:'f',package:'app/a',location:{fileID:'file'}},
    {id:'clean',package:'app/b',location:{fileID:'other'}},{id:'g',package:'app/b',location:{fileID:'other'}}];
  r.files=[{id:'file',package:'app/a',path:'a.go',source:'package a'},
    {id:'other',package:'app/b',path:'b.go',source:'package b'},
    {id:'generated',package:'app/a',path:'gen.go',source:'// Code generated by tool. DO NOT EDIT.\npackage a'}];
  assert.equal(tools.indicators(r,{symbolID:'f'}).level,'watch');
  assert.equal(tools.indicators(r,{symbolID:'g'}).level,'high-concern');
  assert.equal(tools.indicators(r,{symbolID:'clean'}).level,'clear');
  assert.equal(tools.indicators(r,{package:'app/b'}).level,'high-concern');
  assert.equal(tools.indicators(r,{location:{fileID:'generated',line:1}}).level,'not-assessed');
  assert.equal(tools.indicators(r,{symbolID:'external'}).level,'not-assessed');
  assert.equal(tools.indicators(r,{location:{fileID:'other',line:8}}).level,'high-concern');
});

test('SVG indicators show architecture and explicitly snapshot-wide hygiene and allow independent drill-down',()=>{
  const dom=new JSDOM('<svg xmlns="http://www.w3.org/2000/svg"><g></g></svg>',{runScripts:'outside-only'});
  dom.window.eval(fs.readFileSync(path.join(__dirname,'vendor/justgage.umd.js'),'utf8'));
  const drawGauge=(parent,options)=>new dom.window.JustGage({...options,parentNode:parent});
  const group=dom.window.document.querySelector('g');
  let destination='';
  tools.renderNodeIndicators(group,report(),{package:'app/a'},{x:12,y:14,drawGauge,onOpen:section=>{destination=section;}});
  assert.match(group.querySelector('[data-signal="architecture"]').textContent,/Watch/);
  assert.match(group.querySelector('[data-signal="hygiene"]').textContent,/1\/2/);
  assert.equal(group.querySelectorAll('.signal-dial svg').length,2);
  assert.match(group.textContent,/snapshot-wide/i);
  assert.match(group.textContent,/1 error/);
  assert.match(group.textContent,/1 not run/);
  group.querySelector('[data-signal="hygiene"]').dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
  assert.equal(destination,'hygiene');
  group.querySelector('[data-signal="architecture"]').dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true}));
  assert.equal(destination,'architecture');
  tools.renderNodeIndicators(group,report(),{},{drawGauge});
  assert.match(group.querySelector('[data-signal="architecture"]').textContent,/Not assessed/);
  const stale=report();stale.sourceSHA256='changed';
  tools.renderNodeIndicators(group,stale,{package:'app/a'},{drawGauge});
  assert.match(group.querySelector('[data-signal="architecture"]').textContent,/Not assessed/);
  assert.match(group.querySelector('[data-signal="hygiene"]').textContent,/Not assessed/);
  dom.window.close();
});

