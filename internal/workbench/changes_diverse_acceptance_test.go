package workbench

import (
	"context"
	"net/http/httptest"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"github.com/russellbrasser/go-review/internal/changes"
	"github.com/russellbrasser/go-review/internal/review"
)

func TestChangeDiverseInteractiveAcceptance(t *testing.T) {
	root, storage := t.TempDir(), t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.CommandContext(t.Context(), "git", append([]string{"-C", root}, args...)...)
		cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=Fixture", "GIT_AUTHOR_EMAIL=fixture@example.test", "GIT_COMMITTER_NAME=Fixture", "GIT_COMMITTER_EMAIL=fixture@example.test")
		data, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %s (%v)", args, data, err)
		}
		return strings.TrimSpace(string(data))
	}
	write := func(name, text string) {
		t.Helper()
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0600); err != nil {
			t.Fatal(err)
		}
	}
	git("init", "-q")
	write("go.mod", "module example.test/diverse\n\ngo 1.24\nrequire example.test/library v0.0.0\nreplace example.test/library => ./lib\n")
	write("app.go", "package diverse\nfunc First() int {v:=helper();if v<0{return -1};return v}\nfunc Second() int {return helper()}\nfunc helper() int {return 1}\nfunc Repeated(){helper();helper();go helper();fn:=func(){helper()};fn()}\n")
	write("deleted.go", "package diverse\nfunc Gone() int {return helper()}\n")
	write("moved.go", "package diverse\nfunc Moved() int {return 41}\n")
	write("lib/go.mod", "module example.test/library\n\ngo 1.24\n")
	write("lib/app.go", "package library\nfunc Library() int {return 1}\n")
	write("broken/go.mod", "module example.test/broken\n\ngo 1.24\n")
	write("broken/app.go", "package broken\nfunc Existing() int {return 1}\n")
	write("app_test.go", "package diverse\nimport(\"os\";\"testing\")\nfunc TestNever(t *testing.T){os.WriteFile("+strconv.Quote(filepath.Join(root, "EXECUTED"))+",nil,0600)}\n")
	write("inactive.go", "//go:build never_selected\n\npackage diverse\nfunc Inactive() int {return 1}\n")
	write("generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage diverse\nfunc Generated() int {return 1}\n")
	write("excluded.go", "package diverse\nfunc Excluded() int {return 1}\n")
	write("scripts/verify.sh", "#!/bin/sh\ntouch "+strconv.Quote(filepath.Join(root, "EXECUTED"))+"\n")
	write("notes.md", "# Before documentation\n")
	write("config.json", "{\"enabled\":false}\n")
	write("lib/api.wit", "package fixture:api;\nworld service {export run: func();}\n")
	write("asset.bin", "before\x00binary")
	git("add", ".")
	git("commit", "-qm", "before")
	before := git("rev-parse", "HEAD")
	write("app.go", "package diverse\nfunc First() int {v:=helper();if v<0{return -2};return v}\nfunc Second() int {return helper()}\nfunc helper() int {return 2}\nfunc Repeated(){helper();helper();go helper();fn:=func(){helper()};fn()}\n")
	if err := os.Remove(filepath.Join(root, "deleted.go")); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(root, "moved.go")); err != nil {
		t.Fatal(err)
	}
	write("relocated.go", "package diverse\nfunc Relocated() int {return 41}\n")
	write("go.mod", "module example.test/diverse\n\ngo 1.24\nrequire example.test/library v0.0.1\nreplace example.test/library => ./lib\n")
	write("lib/app.go", "package library\nfunc Library() int {return 2}\n")
	write("broken/go.mod", "not a valid module\n")
	write("broken/app.go", "package broken\nfunc Existing() int {return 2}\n")
	write("notes.md", "# After documentation\n")
	write("config.json", "{\"enabled\":true}\n")
	write("lib/api.wit", "package fixture:api;\nworld service {export run: func(value: string);}\n")
	write("asset.bin", "after\x00binary")
	write("inactive.go", "//go:build never_selected\n\npackage diverse\nfunc Inactive() int {return 2}\n")
	write("generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage diverse\nfunc Generated() int {return 2}\n")
	write("excluded.go", "package diverse\nfunc Excluded() int {return 2}\n")
	write("app_test.go", "package diverse\nimport(\"os\";\"testing\")\n// Changed supporting test source; never execute it.\nfunc TestNever(t *testing.T){os.WriteFile("+strconv.Quote(filepath.Join(root, "EXECUTED"))+",nil,0600)}\n")
	if err := os.Chmod(filepath.Join(root, "scripts/verify.sh"), 0755); err != nil {
		t.Fatal(err)
	}
	git("add", ".")
	git("commit", "-qm", "after")
	dirty := git("status", "--porcelain")
	rawDiff := git("diff", "--unified=3", before, "HEAD", "--", "app.go")
	beforeCalls := git("grep", "-n", "helper", before, "--", "*.go")
	afterCalls := git("grep", "-n", "helper", "HEAD", "--", "*.go")
	if !strings.Contains(rawDiff, "return -1") || !strings.Contains(rawDiff, "return -2") ||
		!strings.Contains(beforeCalls, "First") || !strings.Contains(afterCalls, "Second") {
		t.Fatal("raw-diff baseline did not locate the changed error path and helper callers")
	}
	t.Log("Raw-diff task trace: read app.go diff; search helper callers in Before; search helper callers in After. Both workflows expose source, not runtime execution. This is not a human navigation-effort measurement.")
	resolved, err := changes.Resolve(t.Context(), changes.Request{Directory: root, Before: before, After: "HEAD"})
	if err != nil {
		t.Fatal(err)
	}
	c, err := changes.Collect(t.Context(), resolved, storage, review.ReviewScope{VerifyRepository: true, ExcludePaths: []string{"excluded.go"}}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(c.Modules) != 3 || c.Scope.VerifyRepository {
		t.Fatalf("lost independent modules or executed ordinary review policy: %+v", c.Modules)
	}
	accounted := map[string]bool{}
	items := map[string]int{}
	for _, file := range c.Files {
		accounted[file.Before.Path], accounted[file.After.Path] = true, true
		for _, item := range file.Items {
			items[item.ID] = 0
		}
	}
	for _, path := range strings.Split(git("diff", "--name-only", "--no-renames", before, "HEAD"), "\n") {
		if !accounted[path] {
			t.Errorf("Git change absent from inventory: %s", path)
		}
	}
	for _, record := range c.Records {
		for _, id := range record.ItemIDs {
			items[id]++
		}
	}
	for id, count := range items {
		if count != 1 {
			t.Errorf("unique changed item %s accounted %d times", id, count)
		}
	}
	var report *review.Report
	for _, module := range c.Modules {
		if module.Path == "." {
			report, err = c.Report(module.ID, "after")
			if err != nil {
				t.Fatal(err)
			}
		}
	}
	s := New(report)
	s.comparison = c
	server := httptest.NewServer(s.Handler())
	defer server.Close()
	cmd := exec.CommandContext(t.Context(), "node", "--test", "../webui/changes_diverse_ui_test.js")
	cmd.Env = append(os.Environ(), "GO_REVIEW_CHANGE_URL="+server.URL)
	if data, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("diverse UI acceptance: %v\n%s", err, data)
	} else {
		t.Log(string(data))
	}
	changeAcceptanceChat(t, s, c)
	if err := changes.Publish(storage, c); err != nil {
		t.Fatal(err)
	}
	reopened, err := changes.OpenCurrent(storage, resolved.Repository)
	if err != nil || reopened.ID != c.ID {
		t.Fatalf("reopen failed: %v", err)
	}
	state, err := reopened.State()
	if err != nil || state.Version != 1 {
		t.Fatalf("explicit progress did not survive reopen: %+v %v", state, err)
	}
	if _, err := s.queryChanges(context.Background(), changeQueryInput{ComparisonID: "stale", Operation: "files"}); err == nil {
		t.Fatal("foreign comparison accepted")
	}
	if _, err := os.Stat(filepath.Join(root, "EXECUTED")); !os.IsNotExist(err) || git("status", "--porcelain") != dirty || s.current() != report {
		t.Fatal("comparison executed target code, modified checkout, or replaced Application")
	}
}
