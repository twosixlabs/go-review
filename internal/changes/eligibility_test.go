package changes

import (
	"context"
	"strings"
	"testing"

	"github.com/russellbrasser/go-review/internal/review"
)

func TestChangeInventoryDisclosesSemanticEligibilityWithoutHidingFiles(t *testing.T) {
	root := t.TempDir()
	gitFixture(t, root, "init", "-q")
	fixtureFile(t, root, "go.mod", "module example.test/eligibility\n\ngo 1.24\n")
	fixtureFile(t, root, "app.go", "package eligibility\nfunc Entry() {}\n")
	gitFixture(t, root, "add", ".")
	gitFixture(t, root, "commit", "-qm", "before")
	before := gitFixture(t, root, "rev-parse", "HEAD")
	for name, source := range map[string]string{
		"generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage eligibility\nfunc Generated() {}\n",
		"ignored.go":   "package eligibility\nfunc Ignored() {}\n",
		"inactive.go":  "//go:build not_enabled_fixture\n\npackage eligibility\nfunc Inactive() {}\n",
		"app_test.go":  "package eligibility\nimport \"testing\"\nfunc TestEntry(t *testing.T) {}\n",
		"notes.md":     "# Supporting documentation\n",
	} {
		fixtureFile(t, root, name, source)
	}
	gitFixture(t, root, "add", ".")
	gitFixture(t, root, "commit", "-qm", "after")
	r, err := Resolve(context.Background(), Request{Directory: root, Before: before, After: "HEAD"})
	if err != nil {
		t.Fatal(err)
	}
	c, err := Collect(context.Background(), r, t.TempDir(), review.ReviewScope{ExcludePaths: []string{"ignored.go"}}, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]string{"generated.go": "generated", "ignored.go": "excluded", "inactive.go": "build", "app_test.go": "test", "notes.md": "supporting"}
	for _, file := range c.Files {
		if reason, found := want[file.After.Path]; found {
			if !strings.Contains(strings.ToLower(file.AfterEligibility), reason) {
				t.Errorf("%s eligibility %q does not explain %s", file.After.Path, file.AfterEligibility, reason)
			}
			delete(want, file.After.Path)
		}
	}
	if len(want) != 0 {
		t.Fatalf("inventory hid files: %v", want)
	}
}
